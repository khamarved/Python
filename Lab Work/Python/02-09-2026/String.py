# String Operations in Python
s = "Python programming"

print(len(s))
print(s.capitalize())
print(s.upper())
print(s.lower())
print(s.casefold())
print(s.center(20,"*"))
print(s.count("o"))
print(s.find("y"))
print(s.index("y"))
print(s.isalnum())
print(s.isalpha())
print(s.swapcase())
print(s.replace("Python","Java"))
